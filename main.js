function changeLanguage(lang) {
  document.documentElement.lang = lang
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = translations[lang]?.[element.dataset.i18n]
    if (value) element.textContent = value
  })
  document.querySelectorAll("[data-i18n-html]").forEach((element) => {
    const value = translations[lang]?.[element.dataset.i18nHtml]
    if (value) element.innerHTML = value
  })
  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const value = translations[lang]?.[element.dataset.i18nAlt]
    if (value) element.setAttribute("alt", value)
  })
  try {
    localStorage.setItem("preferred_lang", lang)
  } catch {}
}

document.addEventListener("DOMContentLoaded", () => {
  const langSwitch = document.getElementById("lang-switch")
  let savedLang = "es"
  try {
    savedLang = localStorage.getItem("preferred_lang") || "es"
  } catch {}
  if (langSwitch) {
    langSwitch.value = savedLang
    changeLanguage(savedLang)
    langSwitch.addEventListener("change", (event) =>
      changeLanguage(event.target.value),
    )
  }

  const toggle = document.querySelector(".menu-toggle")
  const mobileNav = document.querySelector(".mobile-nav")
  toggle?.addEventListener("click", () => {
    const isOpen = toggle.getAttribute("aria-expanded") === "true"
    toggle.setAttribute("aria-expanded", String(!isOpen))
    mobileNav?.classList.toggle("open", !isOpen)
    document.body.classList.toggle("menu-open", !isOpen)
  })

  const header = document.querySelector(".site-header")
  const updateHeader = () =>
    header?.classList.toggle("scrolled", window.scrollY > 8)
  updateHeader()
  window.addEventListener("scroll", updateHeader, { passive: true })

  const reveals = document.querySelectorAll(".reveal")
  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("visible")
          observer.unobserve(entry.target)
        }
      })
    },
    { threshold: 0.12 },
  )
  reveals.forEach((element) => observer.observe(element))

  const reduceMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches
  const countObserver = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (!entry.isIntersecting) return
        const el = entry.target
        countObserver.unobserve(el)
        const target = Number(el.dataset.count)
        const suffix = el.dataset.suffix || ""
        if (reduceMotion) {
          el.textContent = target + suffix
          return
        }
        const start = performance.now()
        const duration = 1400
        const tick = (now) => {
          const progress = Math.min((now - start) / duration, 1)
          const eased = 1 - Math.pow(1 - progress, 3)
          el.textContent = Math.round(target * eased) + suffix
          if (progress < 1) requestAnimationFrame(tick)
        }
        requestAnimationFrame(tick)
      })
    },
    { threshold: 0.6 },
  )
  document.querySelectorAll("[data-count]").forEach((el) => countObserver.observe(el))
})

